from pathlib import Path
from typing import Any

import pytest
from conftest import Tools
from test_deploy import worker

from wynd.cli import main

CROSSWIND = ("crosswind-workers",)

BINDINGS = {
    "kv_namespaces": [{"binding": "CACHE", "id": "kv"}],
    "d1_databases": [{"binding": "DB", "database_id": "d1"}],
    "r2_buckets": [{"binding": "BUCKET", "bucket_name": "bucket"}],
    "queues": {
        "producers": [{"binding": "JOBS", "queue": "jobs"}],
        "consumers": [{"queue": "jobs"}],
    },
    "durable_objects": {
        "bindings": [
            {"name": "COUNTER", "class_name": "Counter"},
            {"name": "ROOM", "class_name": "Room", "script_name": "chat"},
        ]
    },
    "services": [{"binding": "AUTH", "service": "auth"}],
    "assets": {"directory": "./public", "binding": "ASSETS"},
    "workflows": [{"name": "flow", "binding": "FLOW", "class_name": "Flow"}],
    "ai": {"binding": "AI"},
    "ratelimits": [{"name": "LIMITER", "namespace_id": "1"}],
    "version_metadata": {"binding": "VERSION"},
    "containers": [{"name": "box", "class_name": "Box", "image": "./Dockerfile"}],
    "vars": {"GREETING": "hi", "FLAGS": {"beta": True}, "SIZES": [1, 2]},
}

EXPECTED = """\
# Generated by wynd types. Do not edit.
from __future__ import annotations

from typing import TYPE_CHECKING, Protocol

from workers.bindings import (
    Binding,
    D1Database,
    DurableObjectNamespace,
    Fetcher,
    KVNamespace,
    Queue,
    R2Bucket,
    Workflow,
)
from workers.rpc import JsDict

if TYPE_CHECKING:
    from entry import Counter


class Env(Protocol):
    CACHE: KVNamespace
    DB: D1Database
    BUCKET: R2Bucket
    JOBS: Queue
    COUNTER: DurableObjectNamespace[Counter]
    ROOM: DurableObjectNamespace
    AUTH: Fetcher
    ASSETS: Fetcher
    FLOW: Workflow
    AI: Binding
    LIMITER: Binding
    VERSION: JsDict
    GREETING: str
    FLAGS: dict[str, bool]
    SIZES: list[int]
    API_TOKEN: str
"""


def crosswind_worker(root: Path, settings: dict[str, Any]) -> Path:
    return worker(root, settings, CROSSWIND)


def env_py(root: Path) -> str:
    return (root / "src" / "env.py").read_text()


@pytest.fixture
def project(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    root = crosswind_worker(tmp_path / "worker", BINDINGS)
    (root / ".dev.vars").write_text("# secrets\nAPI_TOKEN=abc\nexport GREETING=yo\n")
    monkeypatch.chdir(root)
    return root


def test_types_writes_an_env_protocol_beside_the_entry_module(
    tools: Tools, project: Path
) -> None:
    assert main(["types"]) == 0

    assert env_py(project) == EXPECTED
    assert tools.wrangler() == []
    assert tools.uv() == []


@pytest.mark.parametrize(
    ("value", "annotation"),
    [
        ("text", "str"),
        (True, "bool"),
        (3, "int"),
        (1.5, "float"),
        (None, "None"),
        ([], "list[Any]"),
        (["a", 1], "list[Any]"),
        ({"a": [1], "b": [2]}, "dict[str, list[int]]"),
    ],
)
def test_json_vars_are_typed_from_their_value(
    tools: Tools,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    value: Any,
    annotation: str,
) -> None:
    monkeypatch.chdir(crosswind_worker(tmp_path / "w", {"vars": {"V": value}}))

    assert main(["types"]) == 0

    assert f"    V: {annotation}\n" in env_py(Path.cwd())
    if "Any" in annotation:
        assert "from typing import Any, Protocol\n" in env_py(Path.cwd())


def test_names_python_cannot_spell_are_left_out(
    tools: Tools, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    settings = {"vars": {"A-B": "x", "class": "x", "OK": "x"}}
    monkeypatch.chdir(crosswind_worker(tmp_path / "w", settings))

    main(["types"])

    assert env_py(Path.cwd()).endswith("class Env(Protocol):\n    OK: str\n")


def test_an_empty_env_is_still_a_protocol(
    tools: Tools, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(crosswind_worker(tmp_path / "w", {}))

    main(["types"])

    assert env_py(Path.cwd()) == (
        "# Generated by wynd types. Do not edit.\n"
        "from __future__ import annotations\n\n"
        "from typing import Protocol\n\n\n"
        "class Env(Protocol):\n    pass\n"
    )


def test_the_environment_brings_its_own_bindings(
    tools: Tools, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    settings = {
        **BINDINGS,
        "logfwdr": {"bindings": [{"name": "LOGS", "destination": "x"}]},
        "env": {"staging": {"kv_namespaces": [{"binding": "STAGED"}]}},
    }
    monkeypatch.chdir(crosswind_worker(tmp_path / "w", settings))

    assert main(["types", "-e", "staging"]) == 0

    # Bindings and vars aren't inherited. assets and logfwdr are, as in Wrangler.
    assert env_py(Path.cwd()).endswith(
        "class Env(Protocol):\n"
        "    ASSETS: Fetcher\n    LOGS: Binding\n    STAGED: KVNamespace\n"
    )


def test_a_base_dir_names_the_main_module_by_its_dotted_path(
    tools: Tools, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    settings = {
        "main": "src/app/entry.py",
        "base_dir": "src",
        "durable_objects": {"bindings": [{"name": "C", "class_name": "Counter"}]},
    }
    root = crosswind_worker(tmp_path / "w", settings)
    monkeypatch.chdir(root)

    main(["types"])

    assert "    from app.entry import Counter\n" in env_py(root)


def test_check_passes_when_env_py_is_current(tools: Tools, project: Path) -> None:
    main(["types"])

    assert main(["types", "--check"]) == 0


def test_check_fails_after_the_config_changes(
    tools: Tools, project: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    main(["types"])
    (project / ".dev.vars").write_text("NEW_SECRET=1\n")

    assert main(["types", "--check"]) == 1

    assert "src/env.py is out of date" in capsys.readouterr().err
    assert env_py(project) == EXPECTED


def test_check_fails_when_env_py_is_missing(tools: Tools, project: Path) -> None:
    assert main(["types", "--check"]) == 1
    assert not (project / "src" / "env.py").exists()


def test_types_needs_crosswind(
    tools: Tools,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    monkeypatch.chdir(worker(tmp_path / "w", {}))

    assert main(["types"]) == 1

    assert "crosswind-workers" in capsys.readouterr().err
    assert not (Path.cwd() / "src" / "env.py").exists()


def test_dev_writes_env_py_only_when_its_text_changes(
    tools: Tools, project: Path
) -> None:
    assert main(["dev"]) == 0
    assert env_py(project) == EXPECTED
    written = (project / "src" / "env.py").stat().st_mtime_ns

    main(["dev"])

    assert (project / "src" / "env.py").stat().st_mtime_ns == written


def test_deploy_stages_the_regenerated_env_py(tools: Tools, project: Path) -> None:
    (project / "src" / "env.py").write_text("# Generated by wynd types. stale\n")

    assert main(["deploy", "--dry-run"]) == 0

    assert env_py(project) == EXPECTED
    staged = project / ".wynd" / "build" / "src" / "env.py"
    assert staged.read_text() == EXPECTED


def test_stock_sdk_projects_get_no_env_py(
    tools: Tools, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(worker(tmp_path / "w", BINDINGS))

    assert main(["deploy", "--dry-run"]) == 0

    assert not (Path.cwd() / "src" / "env.py").exists()


def test_an_env_py_wynd_did_not_write_is_left_alone(
    tools: Tools, project: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    (project / "src" / "env.py").write_text("SETTINGS = {}\n")

    assert main(["dev"]) == 1

    assert "src/env.py" in capsys.readouterr().err
    assert env_py(project) == "SETTINGS = {}\n"
    assert tools.wrangler() == []
