import io
import json
import tomllib
from importlib.metadata import version
from pathlib import Path

import pytest

from wynd.cli import main
from wynd.project import load_project
from wynd.stage import stage_run
from wynd.targets import select_target


def test_init_writes_a_project_wynd_can_build(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    (tmp_path / "wrangler.json").write_text("{}")
    monkeypatch.chdir(tmp_path)

    assert main(["init", "My Worker"]) == 0

    root = tmp_path / "My Worker"
    project = load_project(root, None, None)
    assert project.source.path == root / "cloudflare.config.py"
    assert json.loads(stage_run(project).text)["name"] == "my-worker"
    assert project.dependencies == ("crosswind-workers",)
    pyproject = tomllib.loads((root / "pyproject.toml").read_text())
    assert pyproject["dependency-groups"] == {"dev": [f"wynd>={version('wynd')}"]}
    assert select_target(project.config).version == "3.14"
    assert (root / ".python-version").read_text() == "3.14\n"
    assert (root / "src" / "main.py").is_file()
    assert (root / "src" / "env.py").read_text().startswith("# Generated by wynd")
    assert (root / ".gitignore").read_text() == (".venv/\n.wynd/\n")


def test_init_refuses_a_directory_with_a_project(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "main.py").write_text("mine")
    (tmp_path / "wrangler.toml").write_text("")
    monkeypatch.chdir(tmp_path)

    assert main(["init"]) == 1

    assert "already has src/main.py, wrangler.toml." in capsys.readouterr().err
    assert sorted(p.name for p in tmp_path.iterdir()) == ["src", "wrangler.toml"]
    assert (tmp_path / "src" / "main.py").read_text() == "mine"


def test_init_adds_only_missing_lines_to_a_gitignore(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    (tmp_path / ".gitignore").write_text("*.pyc\n.venv/")
    monkeypatch.chdir(tmp_path)

    assert main(["init"]) == 0

    gitignore = (tmp_path / ".gitignore").read_text()
    assert gitignore == "*.pyc\n.venv/\n.wynd/\n"


def test_init_flags_pick_the_sdk_and_addons(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(tmp_path)

    assert main(["init", "--sdk", "workers-runtime-sdk", "--agents"]) == 0

    project = load_project(tmp_path, None, None)
    assert project.dependencies == ("workers-runtime-sdk", "cf-agents")
    assert "from env" not in (tmp_path / "src" / "main.py").read_text()
    assert not (tmp_path / "src" / "env.py").exists()


def test_init_asks_for_choices_its_flags_leave_out(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    class Terminal(io.StringIO):
        def isatty(self) -> bool:
            return True

    monkeypatch.chdir(tmp_path)
    # Enter for the SDK, then an out-of-range number before a valid one.
    monkeypatch.setattr("sys.stdin", Terminal("\n3\n1\n"))

    # --no-agents leaves only containers to ask about.
    assert main(["init", "--no-agents"]) == 0

    project = load_project(tmp_path, None, None)
    assert project.dependencies == ("crosswind-workers", "containers-py")
