import keyword
import re
from collections.abc import Iterable, Mapping
from typing import Any

from .errors import WyndError
from .project import Project
from .sync import select_sdk
from .wrangler_config import JSON, BindingRef

__all__ = ("render_env", "write_env")

GENERATED_PREFIX = "# Generated by wynd types."
HEADER = f"{GENERATED_PREFIX} Do not edit."

CLASSES = {
    "kv_namespaces": "KVNamespace",
    "d1_databases": "D1Database",
    "r2_buckets": "R2Bucket",
    "queues.producers": "Queue",
    "durable_objects.bindings": "DurableObjectNamespace",
    "services": "Fetcher",
    "assets": "Fetcher",
    "workflows": "Workflow",
    "vectorize": "Vectorize",
    "analytics_engine_datasets": "AnalyticsEngineDataset",
    "images": "ImagesBinding",
    "ratelimits": "RateLimit",
}

DEV_VARS_KEY = re.compile(r"^\s*(?:export\s+)?([A-Za-z_]\w*)\s*=", re.MULTILINE)


def write_env(project: Project, check: bool = False) -> None:
    """Write env.py when its rendered text differs. With `check`, fail instead."""
    sdk = select_sdk(project.dependencies)
    if sdk != "crosswind-workers":
        raise WyndError(
            f"wynd types needs crosswind-workers, because {sdk} has no "
            "workers.bindings."
        )

    config = project.config
    dev_vars = config.source.parent / ".dev.vars"
    secrets = DEV_VARS_KEY.findall(dev_vars.read_text()) if dev_vars.is_file() else []
    text = render_env(
        config.bindings,
        config.vars,
        [*config.required_secrets, *secrets],
        config.entry_module,
    )

    path = config.source_dir / "env.py"
    current = path.read_text() if path.is_file() else None
    if current == text:
        return

    name = path.relative_to(project.root)
    if check:
        raise WyndError(f"{name} is out of date. Run `wynd types` and commit it.")
    if current is not None and not current.startswith(GENERATED_PREFIX):
        raise WyndError(
            f"{name} exists and wynd types didn't write it. Rename it, so Wynd "
            "can write the generated Env there."
        )

    path.write_text(text)
    print(f"wynd: wrote {name}", flush=True)


def render_env(
    bindings: Iterable[BindingRef],
    variables: Mapping[str, JSON],
    secrets: Iterable[str],
    main: str,
) -> str:
    """The text of env.py for a config's bindings, vars and secret names.

    `main` is the entry module's dotted name, which defines the project's
    Durable Object classes.
    """
    attributes, durable_classes = _attributes(bindings, variables, secrets)
    used = {
        word
        for annotation in attributes.values()
        for word in re.findall(r"\w+", annotation)
    }
    durable_classes &= used

    lines = [HEADER, "from __future__ import annotations", ""]
    lines += _import_lines(used, durable_classes, main)
    lines += ["", "class Env(Protocol):"]
    lines += [f"    {name}: {annotation}" for name, annotation in attributes.items()]
    if not attributes:
        lines.append("    pass")

    return "\n".join(lines) + "\n"


def _attributes(
    bindings: Iterable[BindingRef],
    variables: Mapping[str, JSON],
    secrets: Iterable[str],
) -> tuple[dict[str, str], set[str]]:
    """Each Env attribute's annotation, and the Durable Object classes named."""
    attributes: dict[str, str] = {}
    durable_classes: set[str] = set()
    for binding in bindings:
        annotation = CLASSES.get(binding.section, "Binding")
        class_name = binding.class_name
        if binding.section == "version_metadata":
            annotation = "JsDict"
        elif (
            annotation == "DurableObjectNamespace"
            and binding.script_name is None
            and class_name is not None
            and class_name.isidentifier()
        ):
            annotation = f"{annotation}[{class_name}]"
            durable_classes.add(class_name)
        attributes[binding.name] = annotation

    for name, value in variables.items():
        attributes[name] = _json_type(value)

    # A secret replaces a var of the same name, in dev and in production.
    for name in secrets:
        attributes[name] = "str"

    valid = {
        name: annotation
        for name, annotation in attributes.items()
        if name.isidentifier() and not keyword.iskeyword(name)
    }
    return valid, durable_classes


def _import_lines(used: set[str], durable_classes: set[str], main: str) -> list[str]:
    """The import block for the names the annotations use, as ruff writes it."""
    typing_names = {"Protocol", *used & {"Any"}}
    if durable_classes:
        typing_names.add("TYPE_CHECKING")
    lines = [_import("typing", typing_names), ""]

    workers_imports = [
        _import(module, names)
        for module, names in [
            ("workers.bindings", used & {"Binding", *CLASSES.values()}),
            ("workers.rpc", used & {"JsDict"}),
        ]
        if names
    ]
    if workers_imports:
        lines += [*workers_imports, ""]

    if durable_classes:
        lines += ["if TYPE_CHECKING:", _import(main, durable_classes, "    "), ""]

    return lines


def _json_type(value: Any) -> str:
    """The annotation for a var's value as Python receives it."""
    if value is None:
        return "None"
    if isinstance(value, list):
        return f"list[{_common_type(value)}]"
    if isinstance(value, dict):
        return f"dict[str, {_common_type(value.values())}]"

    return {bool: "bool", int: "int", float: "float", str: "str"}.get(
        type(value), "Any"
    )


def _common_type(values: Iterable[Any]) -> str:
    types = {_json_type(value) for value in values}
    return types.pop() if len(types) == 1 else "Any"


def _import(module: str, names: Iterable[str], indent: str = "") -> str:
    """An import statement as ruff's isort and formatter write it."""
    # Constants, then classes, then the rest, as isort's order-by-type does.
    names = sorted(
        names,
        key=lambda n: (0 if n.isupper() else 1 if n[0].isupper() else 2, n.lower()),
    )

    line = f"{indent}from {module} import {', '.join(names)}"
    if len(line) <= 88:
        return line

    body = "".join(f"{indent}    {name},\n" for name in names)
    return f"{indent}from {module} import (\n{body}{indent})"
